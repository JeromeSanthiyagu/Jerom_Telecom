"""Phase 2 preprocessing pipeline: raw CSV -> validated, cleaned parquet.

    load_raw -> validate_raw -> assign record IDs -> cleaning steps
             -> validate_processed -> data/processed/records.parquet

Usage:
    python -m src.preprocessing.processor
"""

from __future__ import annotations

import json
import logging
from typing import Any

import pandas as pd

from src.preprocessing import cleaner
from src.preprocessing.loader import PROCESSED_PATH, load_raw
from src.preprocessing.validator import validate_processed, validate_raw
from src.utils.config import DOCS_DIR, PROCESSED_DIR, load_schema

logger = logging.getLogger(__name__)

REPORT_PATH = PROCESSED_DIR / "cleaning_report.json"
DOCS_REPORT_PATH = DOCS_DIR / "phase2" / "cleaning_report.json"
DATA_DICTIONARY_PATH = DOCS_DIR / "DATA_DICTIONARY.md"


def assign_record_ids(df: pd.DataFrame, schema: dict) -> pd.DataFrame:
    """Add `source_row` (1-based data-row number in the raw CSV) and `record_id`.

    IDs are assigned *before* any row is dropped, so a record_id always points
    back to the same raw row, and dropped rows leave visible gaps. These are
    internal identifiers - the raw dataset has no incident ID of its own.
    """
    ds = schema["dataset"]
    out = df.copy()
    source_row = pd.RangeIndex(1, len(df) + 1)
    out.insert(0, "source_row", source_row.astype("int64"))
    out.insert(0, "record_id", [f"{ds['record_id_prefix']}{i:0{ds['record_id_width']}d}"
                                for i in source_row])
    out["record_id"] = out["record_id"].astype("string")
    return out


def clean(raw: pd.DataFrame, schema: dict) -> tuple[pd.DataFrame, cleaner.CleaningLog]:
    """Run every cleaning step in order. `raw` must already have record IDs."""
    log = cleaner.CleaningLog()
    df = cleaner.map_column_names(raw, schema, log)
    df = cleaner.normalize_text(df, schema, log)
    df = cleaner.standardize_categories(df, schema, log)
    df = cleaner.convert_types(df, schema, log)
    df = cleaner.null_invalid_values(df, schema, log)
    df = cleaner.drop_empty_records(df, schema, log)
    df = cleaner.drop_duplicates(df, log)
    df = cleaner.add_quality_flags(df, schema, log)

    ordered = cleaner.ID_COLUMNS + [c["name"] for c in schema["columns"]]
    flags = [c for c in df.columns if c.startswith("dq_")]
    return df[ordered + flags].reset_index(drop=True), log


def run_pipeline(raw: pd.DataFrame | None = None, write: bool = True) -> tuple[pd.DataFrame, dict[str, Any]]:
    schema = load_schema()
    if raw is None:
        raw = load_raw()

    raw_report = validate_raw(raw, schema)
    raw_report.raise_if_errors()
    for w in raw_report.warnings:
        logger.warning("raw: %s", w)

    df, log = clean(assign_record_ids(raw, schema), schema)

    processed_report = validate_processed(df, schema)
    processed_report.raise_if_errors()

    report = {
        "rows_in": int(len(raw)),
        "rows_out": int(len(df)),
        "rows_dropped": int(len(raw) - len(df)),
        "raw_validation": raw_report.to_dict(),
        "cleaning_log": log.entries,
        "processed_validation": processed_report.to_dict(),
        "quality_flags": {c: int(df[c].sum()) for c in df.columns if c.startswith("dq_")},
    }

    if write:
        PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
        DOCS_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        df.to_parquet(PROCESSED_PATH, index=False)
        text = json.dumps(report, indent=2, ensure_ascii=False, default=str)
        REPORT_PATH.write_text(text, encoding="utf-8")
        DOCS_REPORT_PATH.write_text(text, encoding="utf-8")
        DATA_DICTIONARY_PATH.write_text(render_data_dictionary(schema, df), encoding="utf-8")
        logger.info("wrote %s (%d rows)", PROCESSED_PATH, len(df))
    return df, report


def render_data_dictionary(schema: dict, df: pd.DataFrame) -> str:
    """Generate docs/DATA_DICTIONARY.md from the schema so it can't drift from the code."""
    lines = [
        "# Data Dictionary",
        "",
        "_Generated by `python -m src.preprocessing.processor` from `src/config/schema.yaml` — do not edit by hand._",
        "",
        "All fields below come **directly from the raw dataset** (renamed and type-converted only), "
        "except the identifier and `dq_*` columns, which are added during preprocessing and "
        "are not part of the original data.",
        "",
        "## Identifiers (added)",
        "",
        "| Column | Type | Description |",
        "|---|---|---|",
        "| `record_id` | string | Internal ID `ROW-000001`…, assigned from the raw row position. Not an original incident ID. |",
        "| `source_row` | int64 | 1-based data-row number in the raw CSV (header excluded). |",
        "",
        "## Raw fields",
        "",
        "| Column | Raw header | Type | Unit | Valid range | Role | Missing after cleaning |",
        "|---|---|---|---|---|---|---|",
    ]
    for spec in schema["columns"]:
        rng = spec.get("range")
        rng_txt = f"{rng[0] if rng[0] is not None else '−∞'} … {rng[1] if rng[1] is not None else '∞'}" if rng else (
            ", ".join(spec["allowed"]) if "allowed" in spec else "—")
        lines.append(
            f"| `{spec['name']}` | {spec['raw']} | {df[spec['name']].dtype} | {spec.get('unit', '—')} "
            f"| {rng_txt} | {spec['role']} | {int(df[spec['name']].isna().sum())} |"
        )
    lines += ["", "## Data-quality flags (added)", "", "| Column | Rule | Rows flagged |", "|---|---|---|"]
    for name, expr in schema.get("quality_flags", {}).items():
        lines.append(f"| `{name}` | `{expr}` | {int(df[name].sum())} |")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    _, rep = run_pipeline()
    print(f"rows in={rep['rows_in']} out={rep['rows_out']} dropped={rep['rows_dropped']}")
    for e in rep["cleaning_log"]:
        print(f"  [{e['step']}] {e['column'] or ''} {e['action']}: {e['rows_affected']}")
